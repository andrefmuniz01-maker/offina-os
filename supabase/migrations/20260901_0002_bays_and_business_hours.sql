$$;

create or replace function public.workspace_update_tenant_settings(target_tenant_id bigint, payload jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = public, private
as $$
begin
  if not private.can_manage_tenant(target_tenant_id) then raise exception 'Seu perfil não pode alterar estas configurações.' using errcode = '42501'; end if;
  if payload ? 'openingHours' and not private.is_valid_opening_hours(payload->'openingHours') then
    raise exception 'Horário de funcionamento inválido.' using errcode = '22023';
  end if;
  update public.tenant_settings set legal_name = nullif(payload->>'legalName', ''), document = nullif(payload->>'document', ''), phone = nullif(payload->>'phone', ''), whatsapp = nullif(payload->>'whatsapp', ''), email = nullif(payload->>'email', ''), default_labor_hourly_rate = coalesce((payload->>'defaultLaborHourlyRate')::numeric, 0), default_parts_margin_percent = coalesce((payload->>'defaultPartsMarginPercent')::numeric, 0), default_parts_markup_percent = coalesce((payload->>'defaultPartsMarkupPercent')::numeric, 0), quote_validity_days = coalesce((payload->>'quoteValidityDays')::integer, 7), minimum_margin_percent = coalesce((payload->>'minimumMarginPercent')::numeric, 0), attendant_max_discount_percent = coalesce((payload->>'attendantMaxDiscountPercent')::numeric, 0), quote_message_template = nullif(payload->>'quoteMessageTemplate', ''), opening_hours = case when payload ? 'openingHours' then payload->'openingHours' else opening_hours end, updated_at = now() where tenant_id = target_tenant_id;
  insert into public.audit_logs(tenant_id, actor_user_id, action, entity_type, entity_id, after) values(target_tenant_id, auth.uid(), 'tenant.settings_updated', 'tenant_settings', target_tenant_id, payload);
  return public.workspace_get_tenant_settings(target_tenant_id);
end;
$$;

