-- Capacidade da oficina para a agenda: baias (vagas de atendimento simultâneo)
-- e horário de funcionamento. A disponibilidade da agenda é calculada a partir
-- destes dois, sem nenhum conceito de turno por funcionário (decisão do produto).

create table public.bays (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 80),
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index bays_tenant_active_idx on public.bays(tenant_id, active, sort_order);
select private.apply_tenant_policies('public.bays', false);

alter table public.appointments add column promised_delivery_at timestamptz;
alter table public.appointments add column bay_id bigint references public.bays(id) on delete set null;
create index appointments_bay_idx on public.appointments(tenant_id, bay_id, scheduled_start);

-- Formato canônico de opening_hours (jsonb), por dia da semana:
-- { "monday": { "closed": false, "open": "08:00", "close": "18:00" }, ..., "sunday": { "closed": true } }
create or replace function private.is_valid_opening_hours(value jsonb)
returns boolean
language plpgsql
immutable
as $$
declare
  weekday text;
  day_config jsonb;
  weekdays text[] := array['monday','tuesday','wednesday','thursday','friday','saturday','sunday'];
begin
  if value is null then return true; end if;
  if jsonb_typeof(value) <> 'object' then return false; end if;
  foreach weekday in array weekdays loop
    if value ? weekday then
      day_config := value->weekday;
      if jsonb_typeof(day_config) <> 'object' then return false; end if;
      if coalesce((day_config->>'closed')::boolean, false) = false then
        if day_config->>'open' !~ '^([01]\d|2[0-3]):[0-5]\d$' or day_config->>'close' !~ '^([01]\d|2[0-3]):[0-5]\d$' then
          return false;
        end if;
        if (day_config->>'open') >= (day_config->>'close') then return false; end if;
      end if;
    end if;
  end loop;
  return true;
end;
$$;

