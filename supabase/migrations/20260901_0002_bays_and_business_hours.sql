create or replace function public.workspace_upsert_bay(
  target_tenant_id bigint,
  target_bay_id bigint,
  name_input text,
  active_input boolean default true,
  sort_order_input integer default 0
) returns jsonb
language plpgsql
security invoker
set search_path = public, private
as $$
declare result_id bigint;
begin
  if not private.can_manage_tenant(target_tenant_id) then raise exception 'Seu perfil não pode alterar as baias desta oficina.' using errcode = '42501'; end if;
  if name_input is null or length(trim(name_input)) < 1 or length(trim(name_input)) > 80 then
    raise exception 'Informe um nome de baia válido.' using errcode = '22023';
  end if;
  if target_bay_id is null then
    insert into public.bays(tenant_id, name, active, sort_order) values(target_tenant_id, trim(name_input), coalesce(active_input, true), coalesce(sort_order_input, 0))
    returning id into result_id;
  else
    update public.bays set name = trim(name_input), active = coalesce(active_input, true), sort_order = coalesce(sort_order_input, 0), updated_at = now()
    where id = target_bay_id and tenant_id = target_tenant_id
    returning id into result_id;
    if result_id is null then raise exception 'Baia não encontrada nesta oficina.' using errcode = 'P0002'; end if;
  end if;
  return jsonb_build_object('id', result_id);
end;
$$;

