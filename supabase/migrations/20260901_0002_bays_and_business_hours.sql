-- Agendamento manual: para encaixar um cliente sem orçamento prévio. Cria a
-- OS e o agendamento juntos, do mesmo jeito que a aprovação de orçamento já
-- faz, só que a partir de serviços escolhidos na hora em vez de um orçamento.
-- Duração vem da soma da duração estimada dos serviços (o atendente não
-- escolhe o horário de término diretamente). Bloqueia baia ocupada no
-- intervalo e fora do horário de funcionamento configurado.
create function public.workspace_create_manual_appointment(
  target_tenant_id bigint,
  customer_id_input bigint,
  vehicle_id_input bigint,
  service_ids_input bigint[],
  scheduled_start_input timestamptz,
  bay_id_input bigint,
  promised_delivery_at_input timestamptz default null,
  assigned_to_user_id_input uuid default null,
  notes_input text default null
) returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  bay_name text;
  total_minutes integer;
  scheduled_end_result timestamptz;
  estimated_total_result numeric;
  estimated_cost_result numeric;
  weekday_key text;
  day_config jsonb;
  start_time_of_day text;
  end_time_of_day text;
  work_order_id_result bigint;
  work_order_number_result integer;
  appointment_id_result bigint;
  assigned_member_exists boolean;
begin
  if not private.can_appointments_manage(target_tenant_id) then
    raise exception 'Seu perfil não possui permissão para agendar nesta oficina.' using errcode = '42501';
  end if;
  if scheduled_start_input is null or bay_id_input is null or service_ids_input is null or array_length(service_ids_input, 1) is null then
    raise exception 'Selecione ao menos um serviço, uma baia e um horário.' using errcode = '22023';
  end if;
  if promised_delivery_at_input is not null and promised_delivery_at_input < scheduled_start_input then
    raise exception 'A previsão de entrega não pode ser antes do início do agendamento.' using errcode = '22023';
  end if;
  if not exists (select 1 from public.customers where id = customer_id_input and tenant_id = target_tenant_id) then
    raise exception 'Cliente não encontrado nesta oficina.' using errcode = 'P0002';
  end if;
  if not exists (select 1 from public.vehicles where id = vehicle_id_input and tenant_id = target_tenant_id and customer_id = customer_id_input) then
    raise exception 'Veículo não encontrado para este cliente.' using errcode = 'P0002';
  end if;
  select name into bay_name from public.bays where id = bay_id_input and tenant_id = target_tenant_id and active;
  if bay_name is null then raise exception 'Baia inválida para esta oficina.' using errcode = '22023'; end if;
  if assigned_to_user_id_input is not null then
    select exists(select 1 from public.tenant_members where tenant_id = target_tenant_id and user_id = assigned_to_user_id_input and active) into assigned_member_exists;
    if not assigned_member_exists then raise exception 'O profissional selecionado não pertence a esta oficina ou está inativo.' using errcode = '22023'; end if;
  end if;

  select coalesce(sum(estimated_minutes), 0), coalesce(sum(labor_price), 0), coalesce(sum(estimated_cost), 0)
    into total_minutes, estimated_total_result, estimated_cost_result
  from public.services where tenant_id = target_tenant_id and id = any(service_ids_input) and active;
  if total_minutes is null or total_minutes <= 0 then
    raise exception 'Os serviços selecionados não possuem duração estimada configurada.' using errcode = '22023';
  end if;
  scheduled_end_result := scheduled_start_input + make_interval(mins => total_minutes);

  -- Horário de funcionamento: a aplicação não modela fuso por oficina hoje
  -- (nem em nenhum outro lugar do sistema), então assume-se America/Sao_Paulo
  -- para todas as oficinas, consistente com o restante do produto ser 100%
  -- em português do Brasil / BRL. Sem essa conversão, a comparação em UTC
  -- rejeitaria ou aceitaria horários errados perto da virada do dia.
  weekday_key := lower(trim(to_char(scheduled_start_input at time zone 'America/Sao_Paulo', 'FMDay')));
  select opening_hours->weekday_key into day_config from public.tenant_settings where tenant_id = target_tenant_id;
  if day_config is not null then
    if coalesce((day_config->>'closed')::boolean, false) then
      raise exception 'A oficina está fechada neste dia.' using errcode = '22023';
    end if;
    start_time_of_day := to_char(scheduled_start_input at time zone 'America/Sao_Paulo', 'HH24:MI');
    end_time_of_day := to_char(scheduled_end_result at time zone 'America/Sao_Paulo', 'HH24:MI');
    if day_config->>'open' is not null and day_config->>'close' is not null
      and (start_time_of_day < (day_config->>'open') or end_time_of_day > (day_config->>'close')) then
      raise exception 'O horário escolhido está fora do funcionamento da oficina.' using errcode = '22023';
    end if;
  end if;

  perform 1 from public.appointments
  where tenant_id = target_tenant_id and bay_id = bay_id_input
    and status not in ('cancelled', 'delivered')
    and scheduled_start < scheduled_end_result and scheduled_end > scheduled_start_input
  for update;
  if found then
    raise exception 'Esta baia já está ocupada neste horário.' using errcode = '23505';
  end if;

  perform pg_advisory_xact_lock(target_tenant_id);
  select coalesce(max(number), 0) + 1 into work_order_number_result from public.work_orders where tenant_id = target_tenant_id;
  insert into public.work_orders(tenant_id, number, customer_id, vehicle_id, assigned_to_user_id, estimated_total, estimated_cost_total, notes)
  values(target_tenant_id, work_order_number_result, customer_id_input, vehicle_id_input, assigned_to_user_id_input, estimated_total_result, estimated_cost_result, nullif(trim(coalesce(notes_input, '')), ''))
  returning id into work_order_id_result;

  insert into public.work_order_items(tenant_id, work_order_id, service_id, description, item_type, quantity, unit_price, expected_unit_cost)
  select target_tenant_id, work_order_id_result, s.id, s.name, 'service', 1, s.labor_price, s.estimated_cost
  from public.services s where s.tenant_id = target_tenant_id and s.id = any(service_ids_input) and s.active;

  insert into public.work_order_checklists(tenant_id, work_order_id, label, sort_order)
  values
    (target_tenant_id, work_order_id_result, 'Inspeção inicial', 0),
    (target_tenant_id, work_order_id_result, 'Desmontagem', 1),
    (target_tenant_id, work_order_id_result, 'Instalação', 2),
    (target_tenant_id, work_order_id_result, 'Ajuste', 3),
    (target_tenant_id, work_order_id_result, 'Teste', 4),
    (target_tenant_id, work_order_id_result, 'Finalização', 5);

  insert into public.appointments(tenant_id, customer_id, vehicle_id, work_order_id, assigned_to_user_id, bay, bay_id, scheduled_start, scheduled_end, notes, promised_delivery_at)
  values(target_tenant_id, customer_id_input, vehicle_id_input, work_order_id_result, assigned_to_user_id_input, bay_name, bay_id_input, scheduled_start_input, scheduled_end_result, nullif(trim(coalesce(notes_input, '')), ''), promised_delivery_at_input)
  returning id into appointment_id_result;
  update public.work_orders set appointment_id = appointment_id_result, updated_at = now() where id = work_order_id_result and tenant_id = target_tenant_id;

  insert into public.audit_logs(tenant_id, actor_user_id, action, entity_type, entity_id, after, metadata)
  values(target_tenant_id, auth.uid(), 'appointment.created_manually', 'appointment', appointment_id_result,
    jsonb_build_object('customerId', customer_id_input, 'vehicleId', vehicle_id_input, 'bayId', bay_id_input, 'scheduledStart', scheduled_start_input, 'scheduledEnd', scheduled_end_result, 'promisedDeliveryAt', promised_delivery_at_input, 'serviceIds', service_ids_input),
    jsonb_build_object('workOrderId', work_order_id_result, 'workOrderNumber', work_order_number_result));

  return jsonb_build_object('appointmentId', appointment_id_result, 'workOrderId', work_order_id_result, 'workOrderNumber', work_order_number_result, 'scheduledEnd', scheduled_end_result);
end;
$$;

