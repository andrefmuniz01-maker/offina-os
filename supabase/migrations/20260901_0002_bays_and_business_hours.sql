-- Consulta do calendário: agendamentos por baia num intervalo de datas, com
-- os dados já formatados para o grid semanal/diário no cliente.
create function public.workspace_calendar_appointments(
  target_tenant_id bigint,
  range_start_input timestamptz,
  range_end_input timestamptz
) returns jsonb
language sql
security invoker
set search_path = public, private
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', a.id,
    'bayId', a.bay_id,
    'bayName', a.bay,
    'status', a.status,
    'scheduledStart', a.scheduled_start,
    'scheduledEnd', a.scheduled_end,
    'promisedDeliveryAt', a.promised_delivery_at,
    'customerName', c.name,
    'vehicleName', v.make || ' ' || v.model || coalesce(' · ' || v.plate, ''),
    'workOrderId', a.work_order_id,
    'notes', a.notes
  ) order by a.scheduled_start), '[]'::jsonb)
  from public.appointments a
  join public.customers c on c.id = a.customer_id and c.tenant_id = a.tenant_id
  join public.vehicles v on v.id = a.vehicle_id and v.tenant_id = a.tenant_id
  where a.tenant_id = target_tenant_id
    and private.is_active_member(target_tenant_id)
    and a.scheduled_start < range_end_input and a.scheduled_end > range_start_input
$$;

