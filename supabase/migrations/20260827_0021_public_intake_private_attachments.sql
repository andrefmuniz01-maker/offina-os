-- Intake público Supabase-only. O navegador nunca envia bytes via tRPC: usa uma
-- capacidade efêmera e opaca para gravar somente até cinco objetos em bucket privado.
create table if not exists private.public_quote_intake_throttles (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  whatsapp_fingerprint text not null,
  ip_fingerprint text not null,
  created_at timestamptz not null default now()
);
create index if not exists public_quote_intake_contact_throttle_idx on private.public_quote_intake_throttles(tenant_id, whatsapp_fingerprint, created_at desc);
create index if not exists public_quote_intake_ip_throttle_idx on private.public_quote_intake_throttles(tenant_id, ip_fingerprint, created_at desc);

create table if not exists private.public_quote_upload_capabilities (
  id uuid primary key default gen_random_uuid(),
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  quote_request_id bigint not null unique references public.quote_requests(id) on delete cascade,
  token_hash text not null unique,
  expected_file_count smallint not null check(expected_file_count between 1 and 5),
  expires_at timestamptz not null,
  finalized_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists public_quote_upload_capability_lookup_idx on private.public_quote_upload_capabilities(token_hash, expires_at) where finalized_at is null;

insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
values (
  'quote-request-attachments',
  'quote-request-attachments',
  false,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'video/mp4', 'video/webm', 'video/quicktime']
)
on conflict(id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

create or replace function private.assert_internal_public_intake_caller()
returns void language plpgsql security definer set search_path = public, private as $$
begin
  if auth.role() <> 'service_role' then
    raise exception 'O intake público deve ser encaminhado pelo servidor.' using errcode = '42501';
  end if;
end;
$$;

create or replace function private.assert_public_intake_throttle(
  target_tenant_id bigint,
  normalized_whatsapp text,
  source_ip_fingerprint text
) returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
declare contact_hash text; ip_hash text; contact_attempts integer; ip_attempts integer;
begin
  if normalized_whatsapp !~ '^[0-9]{8,15}$' then raise exception 'Informe um WhatsApp válido com DDD.' using errcode = '22023'; end if;
  if source_ip_fingerprint !~ '^[a-f0-9]{64}$' then raise exception 'Não foi possível validar a origem da solicitação.' using errcode = '22023'; end if;
  contact_hash := encode(extensions.digest(normalized_whatsapp, 'sha256'), 'hex');
  ip_hash := source_ip_fingerprint;
  perform pg_advisory_xact_lock(hashtextextended(target_tenant_id::text || ':' || contact_hash, 0));
  perform pg_advisory_xact_lock(hashtextextended(target_tenant_id::text || ':' || ip_hash, 0));
  select count(*) into contact_attempts from private.public_quote_intake_throttles where tenant_id = target_tenant_id and whatsapp_fingerprint = contact_hash and created_at > now() - interval '10 minutes';
  if contact_attempts > 0 then raise exception 'Recebemos uma solicitação recente deste contato. Aguarde alguns minutos antes de enviar novamente.' using errcode = 'P0001'; end if;
  select count(*) into ip_attempts from private.public_quote_intake_throttles where tenant_id = target_tenant_id and ip_fingerprint = ip_hash and created_at > now() - interval '10 minutes';
  if ip_attempts >= 3 then raise exception 'Recebemos muitas solicitações desta origem. Aguarde alguns minutos antes de tentar novamente.' using errcode = 'P0001'; end if;
  insert into private.public_quote_intake_throttles(tenant_id, whatsapp_fingerprint, ip_fingerprint) values(target_tenant_id, contact_hash, ip_hash);
end;
$$;

create or replace function private.can_insert_public_quote_attachment(target_object_name text, target_metadata jsonb)
returns boolean language sql security definer set search_path = public, private as $$
  select
    target_object_name ~ '^requests/[a-f0-9]{64}/0[1-5]$'
    and coalesce(target_metadata->>'mimetype', '') = any(array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'video/mp4', 'video/webm', 'video/quicktime'])
    and coalesce(target_metadata->>'size', '') ~ '^[0-9]+$'
    and (target_metadata->>'size')::bigint > 0
    and (target_metadata->>'size')::bigint <= 5242880
    and exists (
      select 1 from private.public_quote_upload_capabilities capability
      where capability.token_hash = encode(extensions.digest(split_part(target_object_name, '/', 2), 'sha256'), 'hex')
        and capability.expires_at > now()
        and capability.finalized_at is null
        and capability.expected_file_count >= split_part(target_object_name, '/', 3)::integer
    )
$$;

-- Não existe policy de SELECT, UPDATE, DELETE ou listagem anônima para este bucket.
drop policy if exists public_quote_request_attachment_insert on storage.objects;
create policy public_quote_request_attachment_insert on storage.objects
for insert to anon, authenticated
with check (bucket_id = 'quote-request-attachments' and private.can_insert_public_quote_attachment(name, metadata));

drop policy if exists quote_request_attachment_internal_read on storage.objects;
create policy quote_request_attachment_internal_read on storage.objects
for select to authenticated
using (
  bucket_id = 'quote-request-attachments'
  and exists (
    select 1 from public.attachments attachment
    where attachment.storage_key = name
      and private.is_active_member(attachment.tenant_id)
  )
);

create or replace function private.create_public_quote_upload_capability(
  target_tenant_id bigint,
  target_quote_request_id bigint,
  attachment_count integer
) returns text language plpgsql security definer set search_path = public, private, pg_temp as $$
declare capability_token text;
begin
  if attachment_count = 0 then return null; end if;
  if attachment_count < 1 or attachment_count > 5 then raise exception 'Envie no máximo cinco anexos.' using errcode = '22023'; end if;
  capability_token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into private.public_quote_upload_capabilities(tenant_id, quote_request_id, token_hash, expected_file_count, expires_at)
  values(target_tenant_id, target_quote_request_id, encode(extensions.digest(capability_token, 'sha256'), 'hex'), attachment_count, now() + interval '10 minutes');
  return capability_token;
end;
$$;

create or replace function private.internal_submit_public_quote_request(
  target_tenant_slug text,
  requester_name_input text,
  requester_whatsapp_input text,
  requester_email_input text,
  vehicle_make_input text,
  vehicle_model_input text,
  vehicle_model_year_input integer,
  vehicle_plate_input text,
  vehicle_mileage_input integer,
  selected_service_id bigint,
  service_label_input text,
  description_input text,
  answers_input jsonb,
  attachment_count_input integer,
  source_ip_fingerprint text
) returns jsonb language plpgsql security definer set search_path = public, private, pg_temp as $$
declare target_tenant_id bigint; normalized_whatsapp text; created_request_id bigint; created_request_number integer; upload_token text;
begin
  perform private.assert_internal_public_intake_caller();
  select id into target_tenant_id from public.tenants where slug = trim(lower(target_tenant_slug)) and active and status = 'active' and not is_demo;
  if not found then raise exception 'A oficina solicitada não está disponível.' using errcode = 'P0002'; end if;
  normalized_whatsapp := regexp_replace(trim(requester_whatsapp_input), '\\D', '', 'g');
  perform private.assert_public_intake_throttle(target_tenant_id, normalized_whatsapp, source_ip_fingerprint);
  select request_id, request_number into created_request_id, created_request_number from public.public_submit_quote_request(
    target_tenant_slug, requester_name_input, normalized_whatsapp, requester_email_input, vehicle_make_input, vehicle_model_input,
    vehicle_model_year_input, vehicle_plate_input, vehicle_mileage_input, selected_service_id, service_label_input, description_input, answers_input
  );
  upload_token := private.create_public_quote_upload_capability(target_tenant_id, created_request_id, attachment_count_input);
  insert into public.audit_logs(tenant_id, action, entity_type, entity_id, metadata)
  values(target_tenant_id, 'quote_request.public_intake_submitted', 'quote_request', created_request_id, jsonb_build_object('attachmentsRequested', attachment_count_input, 'source', 'public_link'));
  return jsonb_build_object('requestNumber', created_request_number, 'uploadCapability', upload_token);
end;
$$;

create or replace function private.internal_finalize_public_quote_attachments(
  upload_capability text,
  files_input jsonb
) returns integer language plpgsql security definer set search_path = public, private, pg_temp as $$
declare capability private.public_quote_upload_capabilities%rowtype; entry record; target_key text; object_metadata jsonb; object_size bigint; object_mime text; finalized_count integer := 0;
begin
  perform private.assert_internal_public_intake_caller();
  if upload_capability !~ '^[a-f0-9]{64}$' then raise exception 'Capacidade de upload inválida.' using errcode = '22023'; end if;
  select * into capability from private.public_quote_upload_capabilities where token_hash = encode(extensions.digest(upload_capability, 'sha256'), 'hex') for update;
  if not found or capability.expires_at <= now() or capability.finalized_at is not null then raise exception 'A capacidade de upload expirou ou já foi utilizada.' using errcode = 'P0002'; end if;
  if jsonb_typeof(files_input) <> 'array' or jsonb_array_length(files_input) <> capability.expected_file_count then raise exception 'A lista de anexos não corresponde ao envio autorizado.' using errcode = '22023'; end if;
  if (select count(distinct (value->>'slot')::integer) from jsonb_array_elements(files_input)) <> capability.expected_file_count then raise exception 'Os anexos possuem posições duplicadas.' using errcode = '22023'; end if;
  for entry in select (value->>'slot')::integer as slot, trim(value->>'filename') as filename from jsonb_array_elements(files_input) loop
    if entry.slot < 1 or entry.slot > capability.expected_file_count or entry.filename is null or length(entry.filename) < 1 or length(entry.filename) > 180 then raise exception 'Metadados de anexo inválidos.' using errcode = '22023'; end if;
    target_key := 'requests/' || upload_capability || '/' || lpad(entry.slot::text, 2, '0');
    select metadata into object_metadata from storage.objects where bucket_id = 'quote-request-attachments' and name = target_key;
    if not found then raise exception 'Um dos anexos autorizados não foi enviado.' using errcode = 'P0002'; end if;
    object_mime := object_metadata->>'mimetype';
    object_size := (object_metadata->>'size')::bigint;
    if object_mime <> all(array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'video/mp4', 'video/webm', 'video/quicktime']) or object_size < 1 or object_size > 5242880 then raise exception 'O anexo não atende à política de tipo ou tamanho.' using errcode = '22023'; end if;
    insert into public.attachments(tenant_id, quote_request_id, storage_key, url, filename, mime_type, size_bytes)
    values(capability.tenant_id, capability.quote_request_id, target_key, null, entry.filename, object_mime, object_size);
    finalized_count := finalized_count + 1;
  end loop;
  update private.public_quote_upload_capabilities set finalized_at = now() where id = capability.id;
  insert into public.quote_request_events(tenant_id, quote_request_id, type, metadata)
  values(capability.tenant_id, capability.quote_request_id, 'attachments_added', jsonb_build_object('count', finalized_count));
  return finalized_count;
end;
$$;

